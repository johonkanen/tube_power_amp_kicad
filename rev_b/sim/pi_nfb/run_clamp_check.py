"""Clamp level check for the recommended no-load protection (diodes plate to ground + a clamp per
primary half): does a 600 / 700 / 800 V clamp conduct in normal loaded operation at full
overdrive, and what does it hold the plates to when the speaker is unplugged? Uses the cases of
run_open_load_tran.py. Writes results/clamp_check.md.

    python3 run_clamp_check.py     # about 2 minutes on 30 cores
"""
import os
from multiprocessing import Pool

os.environ.setdefault('OMP_NUM_THREADS', '1')

import run_open_load_tran as R

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, 'results')

# Power amp rev B, third pass: the chosen parts. Per plate one RGP02-20E (2 kV) from ground; per
# primary half two P6KE350CA in series (each VBR 332 / 350 / 368 V at 1 mA, VC 482 V at IPP 1.24 A:
# about 92 ohm dynamic, about 15 pF at high bias), so the string is 664 / 700 / 736 V, 184 ohm.
# Coupling parts as decided: 220 nF / 91k.
R.BASE = dict(cc=220e-9, rgl=91e3)
STRINGS = {664.0: 'VBR min (2 x 332 V)', 700.0: 'nominal', 736.0: 'VBR max (2 x 368 V)'}
CASES = []
for tube in ('EL34', 'KT88', '6L6GC', '6550'):
    for v in STRINGS:
        cl = ['dgnd_rgp', ('tvsr', v, 184.0, 15e-12)]
        for f0 in (100.0, 1000.0):
            CASES.append(((tube, v, 'loaded', f0), dict(R.BASE, tube=tube, fb='100k', load='spk95', cot=1e-9, clamp=cl), R.VMAX_IN, f0, 'steady'))
            CASES.append(((tube, v, 'loaded r8', f0), dict(R.BASE, tube=tube, fb='100k', load='r8', cot=1e-9, clamp=cl), R.VMAX_IN, f0, 'steady'))
            CASES.append(((tube, v, 'unplug', f0), dict(R.BASE, tube=tube, fb='100k', load='spk95', cot=1e-9, clamp=cl, load_switch=0.15), R.VMAX_IN, f0, 'unplug'))


def run(c):
    key, kw, amp, f0, mode = c
    return R.run_case((key, '', kw, amp, f0, mode))


def main():
    with Pool(min(32, os.cpu_count() or 4)) as p:
        res = dict(p.map(run, CASES, chunksize=1))
    md = ["# Clamp level check", "",
          "Generated by `run_clamp_check.py` (power amp rev B copy, chosen parts: RGP02-20E plate to ground, 2x P6KE350CA",
          "per primary half, string 664 / 700 / 736 V with 184 ohm dynamic resistance); 220n / 91k,",
          "Rf 100k, V_ANODE 400 V, 1 nF winding capacitance, 18 V peak at the PI input (full overdrive).",
          "'Loaded': the speaker model or 8 Ω the whole time; 'unplug': the speaker is disconnected at 150 ms.", "",
          "| Tube | Clamp string (VBR at 1 mA) | Case | Frequency | Peak plate to ground (V) | Peak plate to centre tap (V) | Lowest plate (V) | Output peak (V) | Clamp mean power | Clamp energy (unplug: first 10 ms) |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for c in CASES:
        k = c[0]
        r = res[k]
        if 'error' in r:
            md.append(f"| {k[0]} | {k[1]:.0f} V | {k[2]} | {k[3]:.0f} Hz | failed | | | | | |")
            continue
        md.append(f"| {k[0]} | {k[1]:.0f} V | {k[2]} | {k[3]:.0f} Hz | {r['vp_max']:.0f} | {r['vpct']:.0f} | {r['vpmin']:.0f} | {r['out_pk']:.1f} | "
                  f"{r.get('ptvs', 0):.2f} W | {r.get('etvs', 0)*1e3:.1f} mJ |")
    md += ["", "Mean power over the last 100 ms (steady) or after 300 ms (unplug)."]
    with open(os.path.join(RES, 'clamp_check.md'), 'w') as fh:
        fh.write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == '__main__':
    main()
