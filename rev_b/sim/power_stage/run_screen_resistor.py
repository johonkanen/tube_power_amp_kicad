#!/usr/bin/env python3
"""Screen resistor against screen voltage (simulation plan, section 1, Q3 follow-up; D13).

The screen sweep (run_screen_sweep.py, 1k per tube) set the V_SCREEN limit per tube type from
screen dissipation at full overdrive. A larger screen resistor limits the screen current where
the plate swings low, which should allow a higher V_SCREEN (more power) inside the same screen
rating. This sweeps Rg2 (per tube) against V_SCREEN at V_ANODE = 400 V (the assumed maximum,
D14), 70% idle, 1 kHz into 8 ohm, and picks the most power per tube type within the screen rating.

Pg2 is corrected by the push-pull bench error at full signal (see run_screen_sweep.py).
Writes results/screen_resistor.md and results/screen_resistor.png. Usage: python3 run_screen_resistor.py
"""
import math
import os
import sys
from multiprocessing import Pool

import stage
from run_screen_sweep import CORR, DRIVES, p_at

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, 'results')
VA = 400
RG2 = [470, 1000, 2200, 4700]
VS = {'EL34': [350, 370, 400], '6L6GC': [370, 390, 400], '6550': [290, 320, 350, 400],
      'KT88': [320, 350, 380, 400]}


def job(args):
    t, rg2, vs = args
    tubes = [t] * 4
    p = dict(rg2=rg2)
    try:
        b = stage.solve_bias(tubes, VA, 'B', vs, 0.7, p=p)
        pts = [stage.run_drive(tubes, VA, 'B', vs, d, b['vg1'], p=p) for d in DRIVES]
    except Exception as e:  # noqa: BLE001
        return args, dict(error=str(e)[-300:])
    top = pts[-1]
    return args, dict(vg1=b['vg1'][0], vg2_idle=b['vg2'][0], ig2_idle=b['ig2'][0],
                      p5=p_at(pts, 5), p10=p_at(pts, 10), pmax=top['pout'],
                      pg2=max(top['pg2']), pa=max(max(q['pa']) for q in pts),
                      ig2pk=max(top['ig2pk']), thd=[q['thd'] for q in pts], pout=[q['pout'] for q in pts])


def fmt(x, nd=0):
    return '–' if x is None else f'{x:.{nd}f}'


def main():
    os.makedirs(RES, exist_ok=True)
    jobs = [(t, r, v) for t in VS for r in RG2 for v in VS[t]]
    with Pool() as pool:
        res = dict(pool.map(job, jobs))
    L = ['# Power stage: screen resistor against screen voltage\n',
         '> Provisional; section 0 models. Generated by `run_screen_resistor.py`; do not edit.\n',
         f'V_ANODE {VA} V, separate stiff V_SCREEN, Rg2 per tube, 70% idle, 1 kHz into 8 ohm. `Vg2 idle`: at the',
         'screen pin (after the Rg2 drop). `Pg2 corr`: worst tube at full overdrive (160 V peak drive), divided by',
         'the push-pull bench screen-current ratio. `P10%` / `Pmax`: output power at 10% THD / at full overdrive.\n',
         '| Tube | Rg2 | V_SCREEN | Vg2 idle | Vg1 | P5% | P10% | Pmax | Pg2 corr (W) | rating | Ig2 peak (mA) | In rating |',
         '|---|---|---|---|---|---|---|---|---|---|---|---|']
    best = {}
    for t in VS:
        for r in RG2:
            for v in VS[t]:
                x = res[(t, r, v)]
                if 'error' in x:
                    L.append(f'| {t} | {r} | {v} | error | | | | | | | | |')
                    continue
                pc = x['pg2'] / CORR[t]
                ok = pc <= stage.TUBES[t]['pg2']
                L.append(f'| {t} | {r} | {v} | {x["vg2_idle"]:.0f} | {x["vg1"]:.1f} | {fmt(x["p5"])} | {fmt(x["p10"])} | '
                         f'{x["pmax"]:.0f} | {pc:.1f} | {stage.TUBES[t]["pg2"]:.0f} | {x["ig2pk"] * 1e3:.0f} | '
                         f'{"yes" if ok else "**no**"} |')
                if ok and x['p10'] and (t not in best or x['p10'] > best[t][2]):
                    best[t] = (r, v, x['p10'], x['pmax'], pc)
    L += ['', '## Best combination per tube type (most power at 10% THD within the screen rating)\n',
          '| Tube | Rg2 | V_SCREEN | P10% (W) | Pmax (W) | Pg2 corr (W) | Against 1k at the D13 setpoint |', '|---|---|---|---|---|---|---|']
    base_vs = {'EL34': 370, '6L6GC': 390, '6550': 290, 'KT88': 320}
    for t, (r, v, p10, pm, pc) in best.items():
        b = res.get((t, 1000, base_vs[t]), {})
        ref = b.get('p10')
        gain = f'{10 * math.log10(p10 / ref):+.1f} dB ({ref:.0f} W)' if ref else '–'
        L.append(f'| {t} | {r} | {v} | {p10:.0f} | {pm:.0f} | {pc:.1f} | {gain} |')
    open(os.path.join(RES, 'screen_resistor.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))
    plot(res)


def plot(res):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    fig, axs = plt.subplots(1, 4, figsize=(18, 4.5))
    for ax, t in zip(axs, VS):
        for r in RG2:
            xs = [v for v in VS[t] if 'p10' in res[(t, r, v)]]
            ax.plot([res[(t, r, v)]['pg2'] / CORR[t] for v in xs], [res[(t, r, v)]['p10'] or float('nan') for v in xs],
                    marker='o', label=f'Rg2 {r} Ω')
            for v in xs:
                ax.annotate(f'{v}', (res[(t, r, v)]['pg2'] / CORR[t], res[(t, r, v)]['p10'] or 0), fontsize=6)
        ax.axvline(stage.TUBES[t]['pg2'], color='red', lw=0.8, ls='--')
        ax.set_title(f'{t}: P10% against Pg2 (labels: V_SCREEN)', fontsize=9)
        ax.set_xlabel('screen dissipation at full overdrive, corrected (W)')
        ax.set_ylabel('W at 10% THD')
        ax.grid(alpha=0.3)
        ax.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(os.path.join(RES, 'screen_resistor.png'), dpi=100)


if __name__ == '__main__':
    sys.exit(main())
