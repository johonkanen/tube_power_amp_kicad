#!/usr/bin/env python3
"""Screen voltage sweep at fixed V_ANODE (simulation plan, section 1, Q3).

With the section 0 models, screen dissipation at full overdrive exceeds the ratings when the
screen sits at the anode voltage. This sweeps a separate V_SCREEN at V_ANODE = 400 and 450 V
(70% idle) to find the screen voltage per tube type that keeps the screen inside its rating
at full overdrive, and what it costs in power.

Pg2 is also given corrected by the push-pull bench error at full signal (EL34 +5% -> /1.05,
6L6GC -42% -> /0.58, KT88 -30% -> /0.70, 6550 -7% -> /0.93).

Writes results/screen_sweep.md. Usage: python3 run_screen_sweep.py
"""
import os
import sys
from multiprocessing import Pool

import stage

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, 'results')
TYPES = ['EL34', '6L6GC', '6550', 'KT88']
CORR = {'EL34': 1.05, '6L6GC': 0.58, 'KT88': 0.70, '6550': 0.93}
VA = [400, 450]
VS = [250, 300, 350, 400, 450]
DRIVES = [5, 10, 15, 20, 25, 30, 35, 40, 45, 50, 60, 70, 80, 100, 130, 160]


def job(args):
    t, va, vs = args
    tubes = [t] * 4
    try:
        b = stage.solve_bias(tubes, va, 'B', vs, 0.7)
        pts = [stage.run_drive(tubes, va, 'B', vs, d, b['vg1']) for d in DRIVES]
    except Exception as e:  # noqa: BLE001
        return args, dict(error=str(e)[-300:])
    return args, dict(vg1=b['vg1'][0], pts=pts)


def p_at(pts, thd):
    for a, b in reversed(list(zip(pts, pts[1:]))):
        if a['thd'] <= thd < b['thd']:
            return a['pout'] + (thd - a['thd']) / (b['thd'] - a['thd']) * (b['pout'] - a['pout'])
    return None


def main():
    cases = [(t, va, vs) for t in TYPES for va in VA for vs in VS
             if vs <= va and vs <= stage.TUBES[t]['vg2']]
    with Pool() as pool:
        res = dict(pool.map(job, cases))
    L = ['# Power stage: screen voltage sweep (Q3)\n',
         '> Provisional; section 0 models. Generated by `run_screen_sweep.py`; do not edit.\n',
         'Separate V_SCREEN (stiff, 1k per tube), 70% idle, 1 kHz into 8 ohm. `Pg2 max`: worst tube at',
         'full overdrive (160 V peak drive, PI clipped); `corrected`: divided by the push-pull bench',
         'screen-current ratio. `P5%`, `P10%`: output power at 5% / 10% THD; `Pmax`: at full overdrive.\n',
         '| Tube | V_ANODE | V_SCREEN | Vg1 (V) | P5% (W) | P10% (W) | Pmax (W) | Pg2 max (W) | corrected | rating | Pa max (W) |',
         '|---|---|---|---|---|---|---|---|---|---|---|']
    for c in cases:
        r = res[c]
        t, va, vs = c
        if 'error' in r:
            L.append(f'| {t} | {va} | {vs} | error | | | | | | | |')
            continue
        top = r['pts'][-1]
        pg2 = max(top['pg2'])
        corr = pg2 / CORR[t]
        flag = ' **over**' if corr > stage.TUBES[t]['pg2'] else ''
        f = lambda x: '–' if x is None else f'{x:.0f}'  # noqa: E731
        L.append(f'| {t} | {va} | {vs} | {r["vg1"]:.1f} | {f(p_at(r["pts"], 5))} | {f(p_at(r["pts"], 10))} | '
                 f'{top["pout"]:.0f} | {pg2:.1f} | {corr:.1f}{flag} | {stage.TUBES[t]["pg2"]:.0f} | '
                 f'{max(max(p["pa"]) for p in r["pts"]):.1f} |')
    open(os.path.join(RES, 'screen_sweep.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    sys.exit(main())
