#!/usr/bin/env python3
"""V_ANODE / V_SCREEN current at full overdrive (power amp rev B, third pass, 2026-11-23).

stage.py (copied from the master's sim/power_stage) with the decided coupling parts (220 nF / 91k,
5.6k stopper, 1k screen resistors), V_ANODE 400 V (PA-6 maximum), separate V_SCREEN at 90 % of the
lowest screen rating (as run_power_stage.py), idle at 70 % of Pa max, 8 ohm load, 100 Hz and 1 kHz.
Drive: the PI's soft-clipped sine at 160 V peak (deep sine overdrive, the PI clips at 80 V) and a
square wave of +-80 V with 20 us edges (the PI fully clipped: the worst average). The window is the
last 20 ms of 100 ms (coupling caps settled to their blocking state at the 91k / 220n corner of 8 Hz
is slower than that: the 20 ms window after 80 ms holds the drop of the bias shift within a few %).
Writes results/anode_current.md.
"""
import os
import re
from multiprocessing import Pool

import stage

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, 'results')
SETS = {'4x EL34': ['EL34'] * 4, '4x KT88': ['KT88'] * 4, '4x 6L6GC': ['6L6GC'] * 4, '4x 6550': ['6550'] * 4}
VA = 400.0
P = dict(cc=220e-9, rgl=91e3)


def vg2(tubes):
    return min(VA, 0.9 * min(stage.TUBES[t]['vg2'] for t in tubes))


def job(a):
    name, wave, f = a
    tubes = SETS[name]
    p = dict(P, f=f)
    bias = stage.solve_bias(tubes, VA, 'B', vg2(tubes), 0.7, p)['vg1']
    if wave == 'square':
        p['driver'] = ('Bpi1 d1 0 V = {80*tanh(sin(2*pi*f*time)/0.02)}\nBpi2 d2 0 V = {-80*tanh(sin(2*pi*f*time)/0.02)}\n'
                       f'Rpi1 d1 o1 {stage.DEFAULTS["rout_pi"]}\nRpi2 d2 o2 {stage.DEFAULTS["rout_pi"]}')
    net = stage.netlist(tubes, VA, 'B', vg2(tubes), 160.0, bias, p=p)
    t0, t1 = 0.08, 0.10
    net = re.sub(r'from=6\.0+e-02 to=6\.5+e-02|from=0\.06 to=0\.065', f'from={t0} to={t1}', net)
    net = net.replace('tran 2u 0.065 0 2u', f'tran 5u {t1} 0 5u').replace(f'from={60e-3} to={65e-3}', f'from={t0} to={t1}')
    net = net.replace('meas tran ianodepk MIN i(Vanode)', 'meas tran ianodepk MIN i(Vanode)')
    out = stage.run_ngspice(net, timeout=1200)
    m = dict((k.lower(), float(v)) for k, v in re.findall(r'^(\w+)\s*=\s*([-+0-9.eE]+)', out, re.M))
    if 'ianode' not in m:
        return a, None
    return a, dict(ia=abs(m['ianode']), iapk=abs(m['ianodepk']), isc=abs(m.get('iscreen', 0)),
                   pout=m['vrms'] ** 2 / 8.0, iatube=max(m[f'iapk{n}'] for n in range(1, 5)),
                   idle=None)


def main():
    os.makedirs(RES, exist_ok=True)
    jobs = [(n, w, f) for n in SETS for w in ('sine', 'square') for f in (100.0, 1000.0)]
    with Pool() as pool:
        res = dict(pool.map(job, jobs))
    L = ['# V_ANODE current at full overdrive\n', '> Generated by `run_anode_current.py`. ' + __doc__.split('\n\n')[1].replace('\n', ' '), '',
         '| Set | Drive | f (Hz) | Output (W) | V_ANODE average (A) | V_ANODE peak (A) | V_SCREEN average (A) | One plate, peak (A) |',
         '|---|---|---|---|---|---|---|---|']
    for k in jobs:
        r = res[k]
        if r is None:
            L.append(f'| {k[0]} | {k[1]} | {k[2]:.0f} | failed | | | | |')
            continue
        L.append(f'| {k[0]} | {k[1]} | {k[2]:.0f} | {r["pout"]:.0f} | {r["ia"]:.3f} | {r["iapk"]:.3f} | {r["isc"]:.3f} | {r["iatube"]:.3f} |')
    open(os.path.join(RES, 'anode_current.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
